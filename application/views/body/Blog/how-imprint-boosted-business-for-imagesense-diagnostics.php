- Dr Snehal Badjate, Owner.</p><p>

We feel honored to have been able to use our power of automation, reduce the workload and aid so many patients in such a trying time. Imprint hopes to aid a smarter healthcare infrastructure so that we are prepared to fight any kind of battle that may ensue.</p>

