                  The case study belongs to the second wave of covid, when times were uncontrollable. It had stretched the healthcare infrastructure to its maximum and it was extremely important to better manage as well as monitor these facilities. There had been a sense of immense panic. The rush for collecting blood samples, tracking of the field workforce associated with testing laboratories had been next to impossible. During such trying times an automated streamline service was the only way to help in bringing more relief to people at the earliest. Further, it was the need of the hour.</p><p>

Imprint-Medical Field Staff/ phlebotomist Performance Monitoring Software ensures better management and optimum utilisation of field resources as demonstrated in the following case study.</p><p>

<h4>Imprint and Imagesense Diagnostics</h4>

Imagesense Diagnostics, located in Pune, is a well known and well reputed diagnostic center that offers a wide range of services and tests to it's clientele across the city. Every single day, several requests for blood collection are received by this diagnostic center. The center constitutes 50+ phlebotomists, 3 administrators to take care of the holistic operations. On an average it facilitates over hundred sample collections per day. Specifically in the trying times like these, the diagnostic center stood out, selflessly serving the people.</p><p>

Diagnostic centers rely on a team of phlebotomists, who are on-the-move. However, urgent requirements are harder to handle in trying times. It is difficult to trace these on-the-move Phlebotomists and assign a new task to one who is nearest to the desired location. The need of the hour had been better managing & monitoring of their field staff.</p><p>

Therefore, Imagesense Diagnostics had to face a considerable amount of challenges considering that they had to collect a large number of blood samples from across the city. Let us take a look:-</p>
<ul>
<li>Assign & schedule instant appointments for Phlebotomists.</li>
<li>Quickly check availability of Phlebotomist near the client's location.</li>
<li>No means of collecting form data in real-time rather than waiting for a Phlebotomist to reach the office.</li>
<li>No instant/accurate update on payment made by the patients.</li>
<li>Struggling to track the Phlebotomists in real time and accurately manage their time sheets and reimbursements.</li>
<li>Issues to broadcast any information to all the Phlebotomists in one go.</li>
<li>Keeping a record of leaves taken by each Phlebotomist.</li>
<li>No way to trace the exact number of kilometres traveled and working hours clocked by each Phlebotomist every day.</li></ul>
<p>
<h4>The ultimate solution: Imprint</h4>

The client adopted IMPRINT- Medical Field Staff/ phlebotomist Performance Monitoring Software which facilitated the following tasks and improved efficiency by as much as 25-30%:</p><br>
<ul>
<li>Efficient managing and distribution of appointments among Phlebotomist.</li>
<li>Easily checking each Phlebotomist's location and assigning tasks accordingly.</li>
<li>Phlebotomist can fill the dynamic form assigned to them and update all details along with pictures and other required data in real-time.</li>
<li>Collection management now helps the Phlebotomist to update all payments received by them along with the payment mode.</li>
<li>Admin/Manager can easily broadcast any information with the help of Bulletin Board feature, which saves the time and prevents delays or confusion.</li>
<li>Now HR/Admin have the complete record of leaves.</li>
<li>IMPRINT helps to calculate exact distance travelled and daily working hours of each Phlebotomist. Ensures that the manager is updated and reimbursements are managed with ease.</li></ul><p>
Let us consider, what does Imagesense Diagnostics have to stay about us?</p><p>

