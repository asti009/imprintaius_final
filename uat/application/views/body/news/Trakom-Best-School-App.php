<p>15 February 2019 –We are thrilled to announce that, we are the winners of <b>"EdTech Review Corporate Awards 2019"</b> for the <b>"Best School App"</b>. Our school app - <b>"Trakom"</b> is recognized as the best school app of the year. </p>
<p> EdTech Review Corporate awards is one of the biggest gatherings with global participation. <b>EdTech Review team</b> explores new innovation through technology that defines the next frontier in education. It is a community of and for everyone involved in education technology to discover, learn, utilize and share about the best way’s technology can improve learning, teaching, and leading.  </p>
<p> Everything that gets done and contributes to the mission of the team is defined as success of the team. We proudly can say, <b>"Trakom"</b> app is such a contribution from team Asti. We understand the challenges faced by the educational institutions in this digital age, and we have come up with the perfect solution to upgrade schools technologically. We have built trakom, demonstrated its growth and also unleashed the potential for various institutions/schools. The basic idea is to ensure safety and security of students while commuting to and from school and make related information available on fingertips. Communication part of the app helps digitalise all different modes of communication between school and parents.</p>
<p>This smart school app helps in the overall management and the smooth functioning of school activities. It consists of various modules including the GPS and RFID tracking system. It is developed on mobility platform to make solution available on fingertips. Along with smooth functioning, it brings transparency in system; data is made available for future audits. Overall, it helps in bringing more efficiency with less resources in system, hence bringing down operational cost.</p>
<ul class="icons-list">
	<li> <i class=icon-check-2></i>Trakom uses <b>GPS</b> for the real time vehicle tracking of school buses. It helps the parents keep track of current location of their child in real time during commute. </li>
	<li><i class=icon-check-2></i><b>RFID</b> technology is used to ensure the complete safety of students in and out of the schools. It automates attendance in school as well as bus. At the same time, it can be used to monitor restricted areas in premises to avoid any untoward incident and make premises a safer place for children. </li>
	<li><i class=icon-check-2></i>The <b>smart communication</b> feature allows the bidirectional communication between the parents and mentors. Mentors can communicate with the parents through chat completely controlled by school assigned mentors. It facilitates sharing homework’s, attendance, holidays, events and other notices quickly. </li>
	<li><i class=icon-check-2></i>Trakom is also a handy guide for the bus drivers. It informs the drivers about the existing routes, stoppages, alternative routes etc.</li>
</ul>
<p>Are you looking for a perfect school app? Get in touch with our team Asti, we can help you find the right solution.</p>
