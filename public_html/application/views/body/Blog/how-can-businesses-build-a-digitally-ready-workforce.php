However, this has raised a good amount of concern. A considerable amount of employees fear the loss of jobs. People are unwilling to hand over even the most arduous jobs to artificial intelligence or robots. However, the process of automation is nothing to worry about, it is a positive change.</p><p>

Automation will not replace human labour, at least not fully. Let us explain that with an example, consider washing clothes. Previously, we had to wash clothes manually, getting water and washing the clothes. Consider the advent of washing machines. Nowadays a lot of us use washing machines. Washing clothes with the use of washing machines has reduced our labour to a great extent.</p><p>

